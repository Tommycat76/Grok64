#!/usr/bin/env node
/**
 * Writes grok64 core build id (sha256 prefix) for EmulatorJS URL cache-bust + diagnostics.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const coreDir = join(root, "public/system/vice/emulatorjs/data/cores");
const corePath = join(coreDir, "vice_x64sc-grok64-iec-wasm.data");
const bytes = readFileSync(corePath);
const sha256 = createHash("sha256").update(bytes).digest("hex");
const buildId = sha256.slice(0, 12);
const versionedBlob = `vice_x64sc-grok64-iec-wasm-${buildId}.data`;
writeFileSync(join(coreDir, versionedBlob), bytes);

let glueSha12 = "";
const seven = join(root, "node_modules/7zip-bin/linux/x64/7za");
const glueTmp = join(root, ".build/grok64-glue-sha");
const prevGen = join(root, "src/lib/emu/grok64-core-build.generated.ts");
if (existsSync(seven)) {
  rmSync(glueTmp, { recursive: true, force: true });
  mkdirSync(glueTmp, { recursive: true });
  const x = spawnSync(seven, ["x", `-o${glueTmp}`, corePath, "vice_x64sc_libretro.js", "-y"], { stdio: "pipe" });
  if (x.status === 0) {
    try {
      const glueJs = readFileSync(join(glueTmp, "vice_x64sc_libretro.js"));
      glueSha12 = createHash("sha256").update(glueJs).digest("hex").slice(0, 12);
    } catch {
      glueSha12 = "";
    }
  }
}
if (!glueSha12 && existsSync(prevGen)) {
  const prev = readFileSync(prevGen, "utf8");
  const m = prev.match(/GROK64_CORE_GLUE_SHA12 = "([a-f0-9]+)"/);
  if (m) glueSha12 = m[1];
}

const manifest = {
  blob: versionedBlob,
  legacyBlob: "vice_x64sc-grok64-iec-wasm.data",
  sha256,
  buildId,
  glueSha12,
  bytes: bytes.byteLength,
  generatedAt: new Date().toISOString(),
};

const reportPath = join(coreDir, "reports/vice_x64sc.json");
let report = { core: "vice_x64sc", buildStart: buildId, options: { supportsMouse: true, defaultWebGL2: true } };
if (existsSync(reportPath)) {
  try {
    report = { ...JSON.parse(readFileSync(reportPath, "utf8")), buildStart: buildId };
  } catch {
    /* use default */
  }
}
writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);

const publicManifest = join(root, "public/system/vice/emulatorjs/data/cores/grok64-core-manifest.json");
writeFileSync(publicManifest, `${JSON.stringify(manifest, null, 2)}\n`);

const genTs = join(root, "src/lib/emu/grok64-core-build.generated.ts");
mkdirSync(dirname(genTs), { recursive: true });
writeFileSync(
  genTs,
  `/** Auto-generated by scripts/write-grok64-core-manifest.mjs — do not edit by hand. */\n` +
    `export const GROK64_CORE_SHA256 = "${sha256}";\n` +
    `export const GROK64_CORE_BUILD_ID = "${buildId}";\n` +
    `export const GROK64_CORE_GLUE_SHA12 = "${glueSha12}";\n` +
    `export const GROK64_CORE_BYTES = ${bytes.byteLength};\n`,
);

console.log(JSON.stringify({ ok: true, buildId, sha256, bytes: bytes.byteLength }));
